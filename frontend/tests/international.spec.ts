import { test, expect } from '@playwright/test'

test.describe('Internationalization and personalization', () => {
  test.use({ locale: 'en-US' })
  test('automatically uses English and persists manual French preference', async ({ page, isMobile }) => {
    await page.goto('/')
    await expect(page.getByRole('button', { name: /Personalization/ })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('button', { name: /Explore signals/ })).toBeVisible()
    await page.getByRole('button', { name: /Personalization/ }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('radio', { name: /French|Français/ }).check()
    await expect(page.locator('html')).toHaveAttribute('lang', 'fr')
    await expect(page.getByRole('button', { name: /Personnalisation/ })).toBeVisible()
    await dialog.getByRole('button', { name: 'Appliquer' }).click()
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('lang', 'fr')
    await expect(page.getByRole('button', { name: /Personnalisation/ })).toBeVisible()
    // The language switch must not touch recorded channel metadata.
    if (isMobile) await page.getByRole('button', { name: 'Menu' }).click()
    await page.getByRole('button', { name: 'Signal Explorer' }).click()
    await expect(page.getByText('EEG Fz', { exact: true }).first()).toBeVisible()
    await page.getByRole('button', { name: /Personnalisation/ }).click()
    await page.getByRole('dialog').getByRole('radio', { name: /Automatique/ }).check()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  })
  test('manual English selected on a French navigator remains English', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: /Personalization/ }).click()
    await page.getByRole('radio', { name: /English/ }).check()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('button', { name: /Personalization/ })).toBeVisible()
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  })
})

test.describe('Manual QC review', () => {
  test.use({ locale: 'fr-FR' })
  test('marks and removes a segment, preserving the raw signal', async ({ page, isMobile }) => {
    await page.goto('/')
    if (isMobile) await page.getByRole('button', { name: 'Menu' }).click()
    await page.getByRole('button', { name: 'Artifact Review' }).click()
    await expect(page.getByRole('heading', { name: 'Contrôle des artéfacts' })).toBeVisible()
    await page.getByRole('button', { name: 'Examiner le canal' }).click()
    await expect(page.getByText('Fenêtres analysées')).toBeVisible()
    await page.getByRole('button', { name: 'Marquer le segment' }).click()
    await expect(page.getByRole('heading', { name: 'Segments annotés' })).toBeVisible()
    await expect(page.getByText('Artéfact identifié visuellement', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Supprimer segment 1' }).click()
    await expect(page.getByText('Aucun segment marqué.')).toBeVisible()
  })
})
