const english = new Map<string, string>(PAIRS)
const french = new Map<string, string>()
for (const [fr, en] of PAIRS) {
  if (fr !== en && !french.has(en)) french.set(en, fr)
}
export function translateLabel(source: string, locale: Language): string {
  const left = source.match(/^\s*/)?.[0] || ''
  const right = source.match(/\s*$/)?.[0] || ''
  const core = source.trim()
  const translated = locale === 'en' ? english.get(core) : french.get(core)
  return left + (translated || core) + right
}

/** Translate React element labels and presentation props, not scientific data. */
export function localizeTree(node: ReactNode, locale: Language): ReactNode {
  if (typeof node === 'string') return translateLabel(node, locale)
  if (typeof node === 'number' || node == null || typeof node === 'boolean') return node
  if (Array.isArray(node)) return node.map((child) => localizeTree(child, locale))
  if (!isValidElement(node)) return node
  const elem = node as ReactElement<Record<string, unknown>>
  const props = elem.props
  const changes: Record<string, unknown> = {}
  for (const key of ['title', 'description', 'subtitle', 'placeholder', 'aria-label',
    'alt', 'label', 'sub', 'text']) {
    if (typeof props[key] === 'string') changes[key] = translateLabel(props[key] as string, locale)
  }
  if ('children' in props) changes.children = Children.map(props.children as ReactNode,
    (child) => localizeTree(child, locale))
  return cloneElement(elem, changes)
}
